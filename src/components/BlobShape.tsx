export type BlobProps = PropsWithClassName<{
  id: string
  type?: 'rectangle' | 'default'
  outline?: boolean
}>

type BlobShapeProps = BlobProps & {
  pathRef?: RefObject<SVGPathElement | null>
}

/**
 * The static half of a blob: the SVG, drawn in the first of its paths.
 *
 * It carries no animation code, so `AsyncBlob` can render it in the HTML while
 * the animated `Blob` chunk loads. The first path is never shuffled, which
 * keeps the server and the browser drawing the same shape and lets the
 * animation start from exactly what is already on screen.
 */
const BlobShape = ({
  id,
  className,
  type = 'default',
  outline = false,
  pathRef,
}: BlobShapeProps) => {
  const isDefault = type === 'default'

  return (
    <svg
      viewBox={isDefault ? '0 0 200 200' : '0 0 1440 900'}
      xmlns="http://www.w3.org/2000/svg"
      role="presentation"
      className={mergeClassName(
        outline ? 'fill-none stroke-highlight' : 'fill-on-background',
        className,
      )}
      preserveAspectRatio="none"
      aria-hidden
    >
      <path
        ref={pathRef}
        id={id}
        d={isDefault ? blobPaths[0] : rectangleBlobPaths[0]}
        transform={isDefault ? 'translate(100 100)' : undefined}
        style={{ strokeWidth: isDefault ? '1px' : '5px' }}
      />
    </svg>
  )
}

export default BlobShape
